// returns, byte for byte. Same rules as the reference (its README and code), with the hot paths — inline
// Markdown, slug building, template rendering — written to do less work per character.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ------------------------------------------------------------- text

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

function escapeHtml(s) {
  let i = 0;
  const n = s.length;
  while (i < n) {
    const c = s.charCodeAt(i);
    if (c === 38 || c === 60 || c === 62 || c === 34 || c === 39) break;
    i++;
  }
  if (i === n) return s;
  let out = s.slice(0, i);
  for (; i < n; i++) {
    const rep = ESC[s[i]];
    out += rep !== undefined ? rep : s[i];
  }
  return out;
}

const SLUG_MAX = 64;
const slugCache = new Map();

function slugifyRaw(text) {
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

function slugify(text) {
  let v = slugCache.get(text);
  if (v === undefined) {
    // ASCII text is unchanged by NFKD and holds no combining marks: slug it directly.
    let ascii = true;
    for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) > 127) { ascii = false; break; }
    if (ascii) {
      let out = '';
      let gap = false;
      for (let i = 0; i < text.length; i++) {
        const ch = text[i];
        let keep = null;
        if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
        else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
        if (keep === null) { gap = out.length > 0; continue; }
        if (gap) out += '-';
        gap = false;
        out += keep;
      }
      out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
      v = out === '' ? 'untitled' : out;
    } else v = slugifyRaw(text);
    slugCache.set(text, v);
  }
  return v;
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

// ------------------------------------------------------------- front matter

const FM_KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);
const FM_LINE = /^([a-z_]+):(?: (.*))?$/;
const FM_DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const FM_NAME = /^[a-z0-9-]+$/;
const FM_SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const FM_TAG = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = FM_DATE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !FM_TAG.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return FM_NAME.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return FM_SLUG.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') { close = i; break; }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (/^[ \t]*$/.test(line) || line.startsWith('#')) continue;
    const m = FM_LINE.exec(line);
    if (!m) return { error: `line ${i + 1} is not "key: value"` };
    const key = m[1];
    const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
    if (!FM_KEYS.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  let off = 0;
  for (let i = 0; i <= close; i++) off += lines[i].length + 1;
  return { data, body: text.slice(off) };
}

// ------------------------------------------------------------- markdown

const FENCE_OPEN = /^```([A-Za-z0-9_+-]*)[ \t]*$/;
const FENCE_CLOSE = /^```[ \t]*$/;
const HEADING = /^(#{1,6})[ \t]+(.*?)[ \t]*$/;

function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

function headingOf(line) {
  const m = HEADING.exec(line);
  return m === null || m[2] === '' ? null : { depth: m[1].length, text: m[2] };
}

function isHr(line) {
  let pat;
  if (line.startsWith('---')) pat = '---';
  else if (line.startsWith('***')) pat = '***';
  else return false;
  for (let i = 3; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

function endsParagraph(line) {
  if (line === '') return true;
  const c = line[0];
  if (c === ' ' || c === '\t') return isBlank(line);
  if (c === '`') return FENCE_OPEN.test(line);
  if (c === '#') return headingOf(line) !== null;
  if (c === '-' || c === '*') return isHr(line);
  return false;
}

function trimLine(line) {
  const n = line.length;
  if (n === 0) return line;
  const c0 = line.charCodeAt(0);
  const cl = line.charCodeAt(n - 1);
  if (c0 !== 32 && c0 !== 9 && cl !== 32 && cl !== 9) return line;
  let a = 0;
  while (a < n && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  let b = n;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

function lex(src) {
  const lines = src.split('\n');
  const tokens = [];
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (line === '' || isBlank(line)) { i++; continue; }
    const c0 = line[0];
    if (c0 === '`') {
      const fence = FENCE_OPEN.exec(line);
      if (fence !== null) {
        const body = [];
        i++;
        while (i < n && !FENCE_CLOSE.test(lines[i])) body.push(lines[i++]);
        i++;
        tokens.push({ type: 'code', lang: fence[1], lines: body });
        continue;
      }
    }
    if (c0 === '#') {
      const heading = headingOf(line);
      if (heading !== null) {
        tokens.push({ type: 'heading', depth: heading.depth, text: heading.text });
        i++;
        continue;
      }
    }
    if ((c0 === '-' || c0 === '*') && isHr(line)) {
      tokens.push({ type: 'hr' });
      i++;
      continue;
    }
    if (c0 === '>') {
      const body = [];
      while (i < n && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l[1] === ' ' ? l.slice(2) : l.slice(1));
      }
      tokens.push({ type: 'blockquote', lines: body.map(trimLine).filter((l) => l !== '') });
      continue;
    }
    // list?
    let isBullet = false, isOrdered = false, ordStart = 0, firstText = null;
    if ((c0 === '-' || c0 === '*') && line[1] === ' ') { isBullet = true; firstText = line.slice(2); }
    else if (c0 >= '0' && c0 <= '9') {
      const m = /^(\d{1,9})\. (.*)$/.exec(line);
      if (m !== null) { isOrdered = true; ordStart = Number(m[1]); firstText = m[2]; }
    }
    if (isBullet || isOrdered) {
      const items = [[trimLine(firstText)]];
      i++;
      while (i < n) {
        const l = lines[i];
        let text = null;
        if (isBullet) { if ((l[0] === '-' || l[0] === '*') && l[1] === ' ') text = l.slice(2); }
        else {
          const m = /^(\d{1,9})\. (.*)$/.exec(l);
          if (m !== null) text = m[2];
        }
        if (text !== null) { items.push([trimLine(text)]); i++; }
        else if (/^ {2,}\S/.test(l)) { items[items.length - 1].push(trimLine(l)); i++; }
        else break;
      }
      tokens.push({ type: 'list', ordered: isOrdered, start: ordStart, items: items.map((parts) => parts.join('\n')) });
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    tokens.push({ type: 'paragraph', text: body.join('\n') });
  }
  return tokens;
}

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (c !== '*') continue;
    if (s[j + 1] === '*') { j++; continue; }
    return j;
  }
  return -1;
}

/** Escape s[a..b) into the parts array (only called when the range holds a character that needs it, or not). */
function pushEscaped(parts, s, a, b) {
  let start = a;
  for (let i = a; i < b; i++) {
    const rep = ESC[s[i]];
    if (rep !== undefined) {
      if (start < i) parts.push(s.slice(start, i));
      parts.push(rep);
      start = i + 1;
    }
  }
  if (start < b) parts.push(s.slice(start, b));
}

function inline(s, env) {
  const parts = [];
  inlineInto(parts, s, env);
  return parts.join('');
}

function inlineInto(parts, s, env) {
  const n = s.length;
  let i = 0;
  let plain = 0;
  while (i < n) {
    const cc = s.charCodeAt(i);
    if (cc === 38 || cc === 60 || cc === 62 || cc === 34 || cc === 39) { // & < > " '
      if (plain < i) parts.push(s.slice(plain, i));
      parts.push(cc === 38 ? '&amp;' : cc === 60 ? '&lt;' : cc === 62 ? '&gt;' : cc === 34 ? '&quot;' : '&#39;');
      i++;
      plain = i;
      continue;
    }
    if (cc === 92) { // backslash
      if (i + 1 < n && ESCAPABLE.has(s[i + 1])) {
        if (plain < i) parts.push(s.slice(plain, i));
        const rep = ESC[s[i + 1]];
        parts.push(rep !== undefined ? rep : s[i + 1]);
        i += 2;
        plain = i;
      } else i++;
      continue;
    }
    if (cc === 96) { // backtick
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (plain < i) parts.push(s.slice(plain, i));
        parts.push('<code>');
        pushEscaped(parts, s, i + 1, j);
        parts.push('</code>');
        i = j + 1;
        plain = i;
      } else i++;
      continue;
    }
    if (cc === 42) { // star
      if (s.charCodeAt(i + 1) === 42) {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (plain < i) parts.push(s.slice(plain, i));
          parts.push('<strong>');
          inlineInto(parts, s.slice(i + 2, j), env);
          parts.push('</strong>');
          i = j + 2;
          plain = i;
        } else i += 2;
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (plain < i) parts.push(s.slice(plain, i));
        parts.push('<em>');
        inlineInto(parts, s.slice(i + 1, j), env);
        parts.push('</em>');
        i = j + 1;
        plain = i;
      } else i++;
      continue;
    }
    if (cc === 91) { // [
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        if (plain < i) parts.push(s.slice(plain, i));
        parts.push(`<a href="${escapeHtml(env.link(target))}">`);
        inlineInto(parts, s.slice(i + 1, k), env);
        parts.push('</a>');
        i = m + 1;
        plain = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  if (plain < n) parts.push(s.slice(plain, n));
}

function renderMarkdown(src, env) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  for (const t of lex(src)) {
    switch (t.type) {
      case 'heading': {
        const id = uniqueSlug(slugify(t.text), ids);
        const html = inline(t.text, env);
        blocks.push(`<h${t.depth} id="${id}">${html}</h${t.depth}>`);
        if (t.depth === 2 || t.depth === 3) toc.push({ level: t.depth, id, html });
        break;
      }
      case 'code': {
        const cls = t.lang === '' ? '' : ` class="language-${escapeHtml(t.lang)}"`;
        let inner = '';
        for (const l of t.lines) inner += `${escapeHtml(l)}\n`;
        blocks.push(`<pre><code${cls}>${inner}</code></pre>`);
        break;
      }
      case 'hr':
        blocks.push('<hr>');
        break;
      case 'blockquote':
        blocks.push(t.lines.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(t.lines.join('\n'), env)}</p>\n</blockquote>`);
        break;
      case 'list': {
        const tag = t.ordered ? 'ol' : 'ul';
        const open = t.ordered && t.start !== 1 ? `<ol start="${t.start}">` : `<${tag}>`;
        let inner = '';
        for (const item of t.items) inner += `<li>${inline(item, env)}</li>\n`;
        blocks.push(`${open}\n${inner}</${tag}>`);
        break;
      }
      case 'paragraph': {
        const html = inline(t.text, env);
        if (excerpt === null) excerpt = html;
        blocks.push(`<p>${html}</p>`);
        break;
      }
    }
  }
  let html = '';
  for (const b of blocks) html += `${b}\n`;
  return { html, toc, excerpt: excerpt ?? '' };
}

